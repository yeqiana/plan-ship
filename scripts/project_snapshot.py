#!/usr/bin/env python3
"""Read-only Git snapshot of HEAD, tracked changes and untracked file bytes.

Build outputs that are ignored by Git are intentionally not tracked. Keep test
fixtures that matter in version control or identify them in the run logs.
"""
from __future__ import annotations

import hashlib
import subprocess
from pathlib import Path


class SnapshotError(RuntimeError):
    pass


def git(workspace: Path, *args: str) -> bytes:
    p = subprocess.run(["git", "-C", str(workspace), *args], capture_output=True, check=False)
    if p.returncode:
        raise SnapshotError(f"git {' '.join(args)} 失败（exit {p.returncode}）：{p.stderr.decode('utf8', 'replace')[:250]}")
    return p.stdout


def snapshot(workspace: Path) -> dict[str, str]:
    workspace = workspace.resolve()
    root = Path(git(workspace, "rev-parse", "--show-toplevel").decode().strip()).resolve()
    if root != workspace:
        raise SnapshotError(f"--workspace 必须为 Git 项目根：{root}")
    head = git(root, "rev-parse", "HEAD").decode().strip()
    h = hashlib.sha256()
    h.update(b"plan-ship-v1\0")
    h.update(head.encode())
    # Include staged and unstaged changes, without evidence/documents generated by this Skill.
    h.update(git(root, "diff", "--binary", "HEAD", "--", ".", ":(exclude).idea/docs/**"))
    raw = git(root, "ls-files", "--others", "--exclude-standard", "-z")
    for name in sorted(x for x in raw.split(b"\0") if x):
        rel = name.decode("utf-8", "surrogateescape")
        if rel.startswith(".idea/docs/"):
            continue
        f = root / rel
        if f.is_symlink():
            # Never follow untrusted symlinks outside the workspace.
            data = f.readlink().as_posix().encode("utf-8", "surrogateescape")
            digest = hashlib.sha256(data).hexdigest()
        elif f.is_file():
            item = hashlib.sha256()
            with f.open("rb") as stream:
                while chunk := stream.read(1024 * 1024):
                    item.update(chunk)
            digest = item.hexdigest()
        else:
            raise SnapshotError(f"未能读取 untracked 文件：{rel}")
        h.update(name + b"\0" + digest.encode() + b"\0")
    return {"git_head": head, "source_fingerprint": h.hexdigest()}


def safe_inside(path: Path, root: Path) -> bool:
    try:
        path.resolve().relative_to(root.resolve())
        return True
    except ValueError:
        return False


def sha256_file(path: Path) -> str:
    result = hashlib.sha256()
    with path.open("rb") as f:
        while buf := f.read(1024 * 1024):
            result.update(buf)
    return result.hexdigest()
